/**
 * Exports the app copy from lib/i18n.ts and lib/locales (plus the app-only
 * strings in mobile/shared/strings) into the native string resources, in
 * every enabled language (lib/langs.ts), so the copy is written once:
 *
 *   Android  mobile/android/app/src/main/res/values{,-<qualifier>}/strings.xml
 *            mobile/android/app/src/main/res/xml/locales_config.xml
 *            mobile/android/app/src/main/java/com/okjudge/judge/i18n/Strings.kt
 *   iOS      mobile/ios/Judge/Resources/Localizable.xcstrings
 *            mobile/ios/Judge/Generated/L10n.swift
 *            the language lists in Judge/Info.plist and Judge.xcodeproj
 *
 * Run from the repo root:  npx tsx mobile/shared/strings/export-strings.ts
 * CI / pre-commit check:   npx tsx mobile/shared/strings/export-strings.ts --check
 *
 * Placeholders: `{name}` slots become positional arguments numbered by their
 * first appearance in the ENGLISH string (`%1$s` on Android, `%1$@` on iOS),
 * so a translation may use them in any order. Count strings (COUNT_KEYS on
 * the web, APP_COUNT_KEYS here) become plurals with every category the
 * language has; the count is `{n}`, written in ASCII digits as on the web.
 * A language without its app-only file yet reads English for those keys
 * (npm run check:app-locales lists them). Only Node built-ins are used; the
 * generated files are committed so the native builds never need Node.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { COUNT_KEYS, EN, loadedDict, loadLocales, type Key, type PluralForms } from "../../../lib/i18n";
import { ENABLED, LANG_CODES, LANGS, langTag, type Lang } from "../../../lib/langs";
import { stripLeadingEmoji } from "../../../lib/text";
import { checkAppLocale, loadAppLocale } from "./app-locales";
import { APP_COUNT_KEYS, APP_EN, APP_PLURALS_EN } from "./app-strings";
import { EXCLUDE_KEYS, REQUIRED_KEYS, SINGULAR_KEYS, STRIP_EMOJI, WEB_KEYS } from "./keys";

type Category = Intl.LDMLPluralRule;

/** One language's copy, web and app keys together. */
type Copy = { strings: Record<string, string>; plurals: Partial<Record<string, PluralForms>> };

/** A plain string or a plural, ready for the writers. `args` are the slots
 * in English order; a plural's count `{n}` is not among them. */
type Item =
  | { kind: "string"; key: string; args: string[]; text: Record<string, string> }
  | { kind: "plural"; key: string; args: string[]; singular?: string; forms: Record<string, Partial<Record<Category, string>>> };

const MOBILE_DIR = resolve(__dirname, "../..");
const REPO_DIR = resolve(MOBILE_DIR, "..");
const ANDROID_RES = join(MOBILE_DIR, "android/app/src/main/res");
const ANDROID_KT = join(MOBILE_DIR, "android/app/src/main/java/com/okjudge/judge/i18n/Strings.kt");
const IOS_XCSTRINGS = join(MOBILE_DIR, "ios/Judge/Resources/Localizable.xcstrings");
const IOS_SWIFT = join(MOBILE_DIR, "ios/Judge/Generated/L10n.swift");
const IOS_PLIST = join(MOBILE_DIR, "ios/Judge/Info.plist");
const IOS_PROJECT = join(MOBILE_DIR, "ios/Judge.xcodeproj/project.pbxproj");

const HEADER = "Generated by mobile/shared/strings/export-strings.ts from lib/i18n.ts. Do not edit.";
const PLACEHOLDER = /\{([A-Za-z_][A-Za-z0-9_]*)\}/g;
const CATEGORY_ORDER: readonly Category[] = ["zero", "one", "two", "few", "many", "other"];

/** Writing systems whose letters must not be spaced out: the joins of
 * Arabic, the headline bar of the Indic scripts, the stacked marks of Thai,
 * and Hebrew, which has no capitals for a tracked kicker. */
const UNTRACKED_SCRIPTS = new Set([
  "Arabic", "Hebrew", "Thai", "Bengali", "Devanagari", "Gujarati", "Gurmukhi", "Kannada", "Malayalam", "Oriya", "Tamil", "Telugu",
]);

// --- Sources ----------------------------------------------------------------

function matches(pattern: string, key: string): boolean {
  return pattern.endsWith("*") ? key.startsWith(pattern.slice(0, -1)) : key === pattern;
}

function categories(lang: Lang): Category[] {
  const have = new Intl.PluralRules(langTag(lang)).resolvedOptions().pluralCategories;
  return CATEGORY_ORDER.filter((c) => have.includes(c));
}

/** Each enabled language's copy. English fills in only the app-only keys of
 * a language that has no file for them yet. */
async function loadCopies(): Promise<{ copies: Map<Lang, Copy>; missing: Lang[] }> {
  await loadLocales();
  const copies = new Map<Lang, Copy>();
  const missing: Lang[] = [];
  for (const lang of ENABLED) {
    if (lang === "en") {
      copies.set(lang, { strings: { ...EN, ...APP_EN }, plurals: { ...APP_PLURALS_EN } });
      continue;
    }
    const web = loadedDict(lang);
    if (!web) throw new Error(`lib/locales/${lang}.ts did not load`);
    const app = await loadAppLocale(lang);
    if (app) {
      const problems = checkAppLocale(lang, app);
      if (problems.length) throw new Error(`mobile/shared/strings/locales/${lang}.ts:\n  ${problems.join("\n  ")}`);
    } else {
      missing.push(lang);
    }
    copies.set(lang, {
      strings: { ...EN, ...web.strings, ...(app?.strings ?? APP_EN) },
      plurals: { ...web.plurals, ...(app ? app.plurals : APP_PLURALS_EN) },
    });
  }
  return { copies, missing };
}

function placeholders(s: string): string[] {
  const seen: string[] = [];
  for (const m of s.matchAll(PLACEHOLDER)) if (!seen.includes(m[1])) seen.push(m[1]);
  return seen;
}

function checkSlots(key: string, lang: Lang, text: string, allowed: string[]): void {
  const extra = placeholders(text).filter((p) => !allowed.includes(p));
  if (extra.length) throw new Error(`"${key}" in ${lang} uses {${extra.join("}, {")}} which English lacks`);
}

function buildItems(copies: Map<Lang, Copy>): Item[] {
  const webKeys = Object.keys(EN) as Key[];
  for (const pattern of [...WEB_KEYS, ...STRIP_EMOJI]) {
    if (!webKeys.some((k) => matches(pattern, k))) {
      throw new Error(`keys.ts entry "${pattern}" matches no key in lib/i18n.ts`);
    }
  }
  for (const key of [...EXCLUDE_KEYS, ...Object.keys(SINGULAR_KEYS), ...Object.values(SINGULAR_KEYS)]) {
    if (!webKeys.includes(key as Key)) throw new Error(`keys.ts entry "${key}" is not a key in lib/i18n.ts`);
  }
  const selected: string[] = webKeys.filter((key) => WEB_KEYS.some((p) => matches(p, key)) && !EXCLUDE_KEYS.includes(key));
  for (const key of Object.keys(APP_EN)) {
    if (key in EN) throw new Error(`app string "${key}" shadows a web key`);
    selected.push(key);
  }
  const counts = new Set<string>([...COUNT_KEYS, ...APP_COUNT_KEYS]);
  const singulars = new Set(Object.values(SINGULAR_KEYS));
  const strip = (key: string, s: string) => (STRIP_EMOJI.some((p) => matches(p, key)) ? stripLeadingEmoji(s) : s);
  const english = copies.get("en")!.strings;

  const items: Item[] = [];
  for (const key of selected) {
    const slots = placeholders(english[key]);
    if (!counts.has(key)) {
      // A singular may say "{n}" where English spells out 1 (OPTIONAL_SLOTS
      // in lib/locales/check.ts); it only ever stands for 1.
      const one = singulars.has(key);
      const text: Record<string, string> = {};
      for (const [lang, copy] of copies) {
        text[lang] = strip(key, copy.strings[key]);
        if (one) text[lang] = text[lang].split("{n}").join("1");
        checkSlots(key, lang, text[lang], slots);
      }
      items.push({ kind: "string", key, args: slots, text });
      continue;
    }
    if (!slots.includes("n")) throw new Error(`count string "${key}" has no {n}`);
    const singular = SINGULAR_KEYS[key];
    if (singular !== undefined && !selected.includes(singular)) throw new Error(`"${singular}" (for "${key}") is not exported`);
    if (singular !== undefined && placeholders(english[singular]).length) throw new Error(`"${singular}" may not have slots`);
    const forms: Record<string, Partial<Record<Category, string>>> = {};
    for (const [lang, copy] of copies) {
      const base = strip(key, copy.strings[key]);
      forms[lang] = {};
      for (const c of categories(lang)) {
        const form = c === "other" ? base : (copy.plurals[key]?.[c] ?? base);
        checkSlots(key, lang, form, slots);
        forms[lang][c] = form;
      }
    }
    items.push({ kind: "plural", key: key.replace(/\.other$/, ""), args: slots.filter((s) => s !== "n"), singular, forms });
  }
  for (const key of REQUIRED_KEYS) {
    if (!selected.includes(key)) throw new Error(`required key "${key}" is not exported`);
  }
  return items;
}

// --- Names ------------------------------------------------------------------

/** "hero.titleLine1" -> "hero_title_line1" (Android resource name). */
function resName(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[.\-]/g, "_")
    .toLowerCase();
}

/** "hero.titleLine1" -> "heroTitleLine1" (Kotlin/Swift member name). */
function memberName(key: string): string {
  const parts = resName(key).split("_").filter(Boolean);
  return parts.map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join("");
}

const KEYWORDS = new Set([
  // Kotlin hard keywords and Swift keywords that can appear as slot names.
  "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
  "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
  "typeof", "val", "var", "when", "while", "default", "case", "func", "let", "self", "static",
  "struct", "enum", "import", "init", "repeat", "switch", "where", "guard", "defer", "protocol",
]);

function paramName(slot: string): string {
  // `lang` is the generated Swift accessors' own first parameter.
  if (slot === "lang") return "language";
  return KEYWORDS.has(slot) ? `${slot}Value` : slot;
}

function checkUnique(items: Item[]): void {
  const seen = new Map<string, string>();
  for (const item of items) {
    for (const name of [`${item.kind}:${resName(item.key)}`, memberName(item.key)]) {
      const other = seen.get(name);
      if (other && other !== item.key) throw new Error(`"${item.key}" and "${other}" both map to "${name}"`);
      seen.set(name, item.key);
    }
  }
}

/** "zh-Hans" -> "zhHans" (Swift case). */
const swiftCase = (lang: Lang) => lang.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
/** "zh-Hans" -> "ZH_HANS" (Kotlin enum entry). */
const kotlinEntry = (lang: Lang) => lang.replace(/-/g, "_").toUpperCase();
const isRtl = (lang: Lang) => "rtl" in LANGS[lang];
const tracks = (lang: Lang) => !UNTRACKED_SCRIPTS.has(LANGS[lang].script);

/**
 * The res/values directory of a language. Android matches Hebrew and
 * Indonesian under their old codes (iw, in), scripts need the b+ form and
 * regions the -r one.
 */
function androidValuesDir(lang: Lang): string {
  if (lang === "en") return "values";
  if (lang === "he") return "values-iw";
  if (lang === "id") return "values-in";
  const [base, sub] = lang.split("-");
  if (!sub) return `values-${base}`;
  return sub.length === 4 ? `values-b+${base}+${sub}` : `values-${base}-r${sub}`;
}

// --- Formatting -------------------------------------------------------------

/** Positional format string: literal % doubled (only when it is formatted),
 * each slot replaced by its index in `args`. Other slots stay as written. */
function formatString(s: string, args: string[], spec: (index: number) => string): string {
  const escaped = args.length ? s.replace(/%/g, "%%") : s;
  return escaped.replace(PLACEHOLDER, (whole, name: string) => {
    const i = args.indexOf(name);
    return i < 0 ? whole : spec(i + 1);
  });
}

function androidEscape(s: string): string {
  let out = s
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    // aapt collapses runs of spaces and trims the ends; keep them literal.
    .replace(/ {2,}/g, (m) => " " + "\\u0020".repeat(m.length - 1))
    .replace(/^ | $/g, "\\u0020");
  if (out.startsWith("@") || out.startsWith("?")) out = `\\${out}`;
  return out;
}

function androidXml(items: Item[], lang: Lang): string {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} -->`, "<resources>"];
  for (const item of items) {
    if (item.kind === "string") {
      const raw = item.text[lang];
      const value = androidEscape(formatString(raw, item.args, (i) => `%${i}$s`));
      const formatted = !item.args.length && raw.includes("%") ? ' formatted="false"' : "";
      lines.push(`    <string name="${resName(item.key)}"${formatted}>${value}</string>`);
    } else {
      lines.push(`    <plurals name="${resName(item.key)}">`);
      for (const [q, form] of Object.entries(item.forms[lang])) {
        const value = androidEscape(formatString(form, ["n", ...item.args], (i) => `%${i}$s`));
        lines.push(`        <item quantity="${q}">${value}</item>`);
      }
      lines.push("    </plurals>");
    }
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

function localesConfig(): string {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${HEADER} -->`,
    '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
    ...ENABLED.map((lang) => `    <locale android:name="${lang}" />`),
    "</locale-config>",
    "",
  ].join("\n");
}

function kotlin(items: Item[]): string {
  const members: string[] = [];
  const plain: string[] = [];
  for (const item of items) {
    const name = memberName(item.key);
    const id = resName(item.key);
    const params = item.args.map((a) => `${paramName(a)}: String`);
    const args = item.args.map((a) => `, ${paramName(a)}`).join("");
    if (item.kind === "plural") {
      const plural = `res.getQuantityString(R.plurals.${id}, n, n.toString()${args})`;
      const body = item.singular ? `if (n == 1) res.getString(R.string.${resName(item.singular)}) else ${plural}` : plural;
      members.push(`    fun ${name}(${["n: Int", ...params].join(", ")}): String = ${body}`);
    } else if (item.args.length === 0) {
      members.push(`    val ${name}: String get() = res.getString(R.string.${id})`);
      plain.push(`        "${item.key}" -> R.string.${id}`);
    } else {
      members.push(`    fun ${name}(${params.join(", ")}): String = res.getString(R.string.${id}${args})`);
    }
  }
  const entries = LANG_CODES.map((lang, i) => {
    const { tag, native } = LANGS[lang];
    const end = i === LANG_CODES.length - 1 ? ";" : ",";
    return `    ${kotlinEntry(lang)}(${JSON.stringify(lang)}, ${JSON.stringify(tag)}, ${JSON.stringify(native)}, ${isRtl(lang)}, ${tracks(lang)})${end}`;
  });
  return [
    `// ${HEADER}`,
    "package com.okjudge.judge.i18n",
    "",
    "import android.content.res.Resources",
    "import com.okjudge.judge.R",
    "import java.util.Locale",
    "",
    "/**",
    " * Every language of lib/langs.ts, so stored verdicts in any of them decode.",
    " * [tag] is the code the server takes, [bcp47] the tag to format with,",
    " * [nativeName] what the language picker shows. Only [enabled] ones have strings.",
    " */",
    "enum class AppLang(",
    "    val tag: String,",
    "    val bcp47: String,",
    "    val nativeName: String,",
    "    val rtl: Boolean,",
    "    /** False for scripts that must not be letter-spaced (Arabic, Hebrew, Thai, Indic). */",
    "    val tracking: Boolean,",
    ") {",
    ...entries,
    "",
    "    val locale: Locale get() = Locale.forLanguageTag(bcp47)",
    "",
    "    companion object {",
    `        val enabled: List<AppLang> = listOf(${ENABLED.map(kotlinEntry).join(", ")})`,
    "",
    "        fun fromTag(tag: String?): AppLang? = entries.firstOrNull { it.tag == tag }",
    "    }",
    "}",
    "",
    "/**",
    " * Typed access to the shared copy. Pass the Resources of the language to",
    " * render in (see AppLang), never rely on the process locale directly.",
    " */",
    "class Strings(private val res: Resources) {",
    ...members,
    "",
    "    /** A placeholder-free string by its lib/i18n.ts key, for keys built at",
    "     * runtime (\"badge.$type\", \"kind.$kind\"). Null when unknown. */",
    "    fun text(key: String): String? = idOf(key)?.let { res.getString(it) }",
    "",
    "    companion object {",
    "        fun idOf(key: String): Int? = when (key) {",
    ...plain.map((l) => `    ${l}`),
    "            else -> null",
    "        }",
    "    }",
    "}",
    "",
  ].join("\n");
}

/** JSON in Xcode's own .xcstrings layout (sorted keys, `"key" : value`), so
 * opening the catalog in Xcode does not rewrite the whole file. */
function xcodeJson(value: unknown, indent = ""): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  const keys = Object.keys(value as object).sort();
  if (!keys.length) return "{\n\n}";
  const body = keys
    .map((k) => `${inner}${JSON.stringify(k)} : ${xcodeJson((value as Record<string, unknown>)[k], inner)}`)
    .join(",\n");
  return `{\n${body}\n${indent}}`;
}

function xcstrings(items: Item[]): string {
  const unit = (v: string) => ({ stringUnit: { state: "translated", value: v } });
  const strings: Record<string, unknown> = {};
  for (const item of items) {
    const localizations: Record<string, unknown> = {};
    for (const lang of ENABLED) {
      if (item.kind === "string") {
        localizations[lang] = unit(formatString(item.text[lang], item.args, (i) => `%${i}$@`));
      } else {
        // The count is the one format argument; L10n fills the other slots,
        // which stay as {name} here.
        const plural: Record<string, unknown> = {};
        for (const [q, form] of Object.entries(item.forms[lang])) plural[q] = unit(formatString(form, ["n"], () => "%lld"));
        localizations[lang] = { variations: { plural } };
      }
    }
    strings[item.key] = { comment: HEADER, extractionState: "manual", localizations };
  }
  return `${xcodeJson({ sourceLanguage: "en", strings, version: "1.0" })}\n`;
}

function swift(items: Item[]): string {
  const members: string[] = [];
  const plain: string[] = [];
  for (const item of items) {
    const name = memberName(item.key);
    const key = JSON.stringify(item.key);
    const params = item.args.map((a) => `, ${paramName(a)}: String`).join("");
    if (item.kind === "plural") {
      const slots = item.args.length ? `, [${item.args.map((a) => `"${a}": ${paramName(a)}`).join(", ")}]` : "";
      const plural = `plural(${key}, lang, n${slots})`;
      const body = item.singular ? `n == 1 ? string(${JSON.stringify(item.singular)}, lang) : ${plural}` : plural;
      members.push(`    static func ${name}(_ lang: AppLang, n: Int${params}) -> String { ${body} }`);
    } else if (item.args.length === 0) {
      members.push(`    static func ${name}(_ lang: AppLang) -> String { string(${key}, lang) }`);
      plain.push(`        ${key},`);
    } else {
      const args = item.args.map(paramName).join(", ");
      members.push(`    static func ${name}(_ lang: AppLang${params}) -> String { format(${key}, lang, ${args}) }`);
    }
  }
  const switchOver = (value: (lang: Lang) => string) =>
    LANG_CODES.map((lang) => `        case .${swiftCase(lang)}: return ${value(lang)}`);
  const cases = LANG_CODES.map((lang) => (lang.includes("-") ? `${swiftCase(lang)} = ${JSON.stringify(lang)}` : lang));
  const untracked = LANG_CODES.filter((l) => !tracks(l)).map((l) => `.${swiftCase(l)}`);
  const rtl = LANG_CODES.filter(isRtl).map((l) => `.${swiftCase(l)}`);
  return [
    `// ${HEADER}`,
    "import Foundation",
    "",
    "/// Every language of lib/langs.ts, so stored verdicts in any of them decode;",
    "/// the raw value is the code the server takes. Strings are looked up in the",
    "/// matching .lproj bundle, so the in-app language never depends on the",
    "/// device locale. Only `enabled` ones have strings.",
    "enum AppLang: String, CaseIterable, Codable, Sendable {",
    `    case ${cases.join(", ")}`,
    "",
    "    /// The languages with strings, English first, in the website's order.",
    `    static let enabled: [AppLang] = [${ENABLED.map((l) => `.${swiftCase(l)}`).join(", ")}]`,
    "",
    "    /// BCP-47 tag for dates, numbers and prices (lib/langs.ts `tag`).",
    "    var tag: String {",
    "        switch self {",
    ...switchOver((l) => JSON.stringify(LANGS[l].tag)),
    "        }",
    "    }",
    "",
    "    /// The language's name in itself, for the language picker.",
    "    var nativeName: String {",
    "        switch self {",
    ...switchOver((l) => JSON.stringify(LANGS[l].native)),
    "        }",
    "    }",
    "",
    "    var isRTL: Bool {",
    "        switch self {",
    `        case ${rtl.join(", ")}: return true`,
    "        default: return false",
    "        }",
    "    }",
    "",
    "    /// False for scripts that must not be letter-spaced (Arabic, Hebrew, Thai, Indic).",
    "    var tracks: Bool {",
    "        switch self {",
    `        case ${untracked.join(", ")}: return false`,
    "        default: return true",
    "        }",
    "    }",
    "",
    "    var bundle: Bundle {",
    '        Bundle.main.path(forResource: rawValue, ofType: "lproj").flatMap(Bundle.init(path:)) ?? .main',
    "    }",
    "",
    "    var locale: Locale { Locale(identifier: tag) }",
    "",
    "    /// The locale counts are written in: the language's plural rules, but",
    "    /// ASCII digits, as the website writes them.",
    '    var countLocale: Locale { Locale(identifier: tag + "@numbers=latn") }',
    "}",
    "",
    "/// Typed access to the shared copy.",
    "enum L10n {",
    ...members,
    "",
    "    /// A placeholder-free string by its lib/i18n.ts key, for keys built at",
    '    /// runtime ("badge.\\(type)"). Nil when unknown.',
    "    static func text(_ key: String, _ lang: AppLang) -> String? {",
    "        plainKeys.contains(key) ? string(key, lang) : nil",
    "    }",
    "",
    "    private static let plainKeys: Set<String> = [",
    ...plain,
    "    ]",
    "",
    "    private static func string(_ key: String, _ lang: AppLang) -> String {",
    "        NSLocalizedString(key, tableName: \"Localizable\", bundle: lang.bundle, comment: \"\")",
    "    }",
    "",
    "    private static func format(_ key: String, _ lang: AppLang, _ args: any CVarArg...) -> String {",
    "        String(format: string(key, lang), locale: lang.locale, arguments: args)",
    "    }",
    "",
    "    /// A count string: the catalog picks the plural form for `n`, the other",
    "    /// slots are filled in by name.",
    "    private static func plural(_ key: String, _ lang: AppLang, _ n: Int, _ slots: [String: String] = [:]) -> String {",
    "        var text = String(format: string(key, lang), locale: lang.countLocale, n)",
    "        for (slot, value) in slots {",
    '            text = text.replacingOccurrences(of: "{\\(slot)}", with: value)',
    "        }",
    "        return text",
    "    }",
    "}",
    "",
  ].join("\n");
}

// --- The language lists in hand-kept files ------------------------------------

function replaceOnce(text: string, re: RegExp, replacement: string, what: string): string {
  if (!re.test(text)) throw new Error(`could not find ${what}`);
  return text.replace(re, replacement);
}

/** Info.plist with CFBundleLocalizations listing every enabled language, so
 * iOS and the App Store show them as supported. */
function infoPlist(current: string): string {
  const eol = current.includes("\r\n") ? "\r\n" : "\n";
  const list = ENABLED.map((l) => `\t\t<string>${l}</string>`).join(eol);
  return replaceOnce(
    current,
    /(<key>CFBundleLocalizations<\/key>\r?\n\t<array>\r?\n)[\s\S]*?(\r?\n\t<\/array>)/,
    `$1${list}$2`,
    "CFBundleLocalizations in Info.plist",
  );
}

/** The Xcode project's knownRegions, every enabled language plus Base. */
function pbxproj(current: string): string {
  const eol = current.includes("\r\n") ? "\r\n" : "\n";
  const list = [...ENABLED.map((l) => (l.includes("-") ? `"${l}"` : l)), "Base"].map((l) => `\t\t\t\t${l},`).join(eol);
  return replaceOnce(current, /(knownRegions = \(\r?\n)[\s\S]*?(\r?\n\t\t\t\);)/, `$1${list}$2`, "knownRegions in project.pbxproj");
}

// --- Main -------------------------------------------------------------------

/** Generated strings.xml files of languages no longer exported. */
function staleValues(expected: Set<string>): string[] {
  return readdirSync(ANDROID_RES)
    .filter((d) => d.startsWith("values"))
    .map((d) => join(ANDROID_RES, d, "strings.xml"))
    .filter((p) => existsSync(p) && !expected.has(p) && readFileSync(p, "utf8").includes(HEADER));
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const { copies, missing } = await loadCopies();
  const items = buildItems(copies);
  checkUnique(items);
  const read = (path: string) => (existsSync(path) ? readFileSync(path, "utf8") : "");
  const outputs: [string, string][] = [
    ...ENABLED.map((lang): [string, string] => [join(ANDROID_RES, androidValuesDir(lang), "strings.xml"), androidXml(items, lang)]),
    [join(ANDROID_RES, "xml/locales_config.xml"), localesConfig()],
    [ANDROID_KT, kotlin(items)],
    [IOS_XCSTRINGS, xcstrings(items)],
    [IOS_SWIFT, swift(items)],
    [IOS_PLIST, infoPlist(read(IOS_PLIST))],
    [IOS_PROJECT, pbxproj(read(IOS_PROJECT))],
  ];
  const leftover = staleValues(new Set(outputs.map(([p]) => p)));
  let stale = 0;
  for (const [path, content] of outputs) {
    const rel = relative(REPO_DIR, path).replace(/\\/g, "/");
    if (read(path) === content) continue;
    if (check) {
      stale++;
      console.error(`stale: ${rel}`);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, "utf8");
    console.log(`wrote ${rel}`);
  }
  for (const path of leftover) {
    const rel = relative(REPO_DIR, path).replace(/\\/g, "/");
    if (check) {
      stale++;
      console.error(`stale: ${rel} (language no longer exported)`);
    } else {
      rmSync(path);
      console.log(`removed ${rel}`);
    }
  }
  const plurals = items.filter((i) => i.kind === "plural").length;
  console.log(`${items.length} entries (${plurals} plurals) in ${ENABLED.length} languages`);
  if (missing.length) console.log(`English stands in for the app-only strings in: ${missing.join(", ")}`);
  if (stale) {
    console.error("Run: npx tsx mobile/shared/strings/export-strings.ts");
    process.exit(1);
  }
}

void main();
