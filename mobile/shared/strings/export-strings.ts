/**
 * Exports the app copy from lib/i18n.ts (plus mobile/shared/strings/app-strings.ts)
 * into the native string resources, so EN/TR copy is written once:
 *
 *   Android  mobile/android/app/src/main/res/values{,-tr}/strings.xml
 *            mobile/android/app/src/main/java/com/okjudge/judge/i18n/Strings.kt
 *   iOS      mobile/ios/Judge/Resources/Localizable.xcstrings
 *            mobile/ios/Judge/Generated/L10n.swift
 *
 * Run from the repo root:  npx tsx mobile/shared/strings/export-strings.ts
 * CI / pre-commit check:   npx tsx mobile/shared/strings/export-strings.ts --check
 *
 * Placeholders: `{name}` slots become positional arguments numbered by their
 * first appearance in the ENGLISH string (`%1$s` on Android, `%1$@` on iOS),
 * so a Turkish string may use them in any order. Keys ending in ".one" /
 * ".other" become one plural resource whose count is `{n}` (`%1$d` / `%lld`);
 * a bare key with only a ".one" next to it ("pricing.pack") is the other form.
 * Only Node built-ins are used; the generated files are committed so the
 * native builds never need Node.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { STRINGS } from "../../../lib/i18n";
import { stripLeadingEmoji } from "../../../lib/text";
import { APP_STRINGS } from "./app-strings";
import { EXCLUDE_KEYS, REQUIRED_KEYS, STRIP_EMOJI, WEB_KEYS } from "./keys";

type Lang = "en" | "tr";
const LANGS: readonly Lang[] = ["en", "tr"];

/** One exported string (or one plural form before grouping). */
type Entry = { key: string; en: string; tr: string };

/** A plain string or a plural group, ready for the writers. */
type Item =
  | { kind: "string"; key: string; text: Record<Lang, string>; args: string[] }
  | { kind: "plural"; key: string; forms: Record<Lang, { one: string; other: string }> };

const MOBILE_DIR = resolve(__dirname, "../..");
const REPO_DIR = resolve(MOBILE_DIR, "..");
const ANDROID_RES = join(MOBILE_DIR, "android/app/src/main/res");
const ANDROID_KT = join(MOBILE_DIR, "android/app/src/main/java/com/okjudge/judge/i18n/Strings.kt");
const IOS_XCSTRINGS = join(MOBILE_DIR, "ios/Judge/Resources/Localizable.xcstrings");
const IOS_SWIFT = join(MOBILE_DIR, "ios/Judge/Generated/L10n.swift");

const HEADER = "Generated by mobile/shared/strings/export-strings.ts from lib/i18n.ts. Do not edit.";
const PLACEHOLDER = /\{([A-Za-z_][A-Za-z0-9_]*)\}/g;

// --- Selection --------------------------------------------------------------

function matches(pattern: string, key: string): boolean {
  return pattern.endsWith("*") ? key.startsWith(pattern.slice(0, -1)) : key === pattern;
}

function selectEntries(): Entry[] {
  const webKeys = Object.keys(STRINGS.en) as (keyof typeof STRINGS.en)[];
  for (const pattern of [...WEB_KEYS, ...STRIP_EMOJI]) {
    if (!webKeys.some((k) => matches(pattern, k))) {
      throw new Error(`keys.ts entry "${pattern}" matches no key in lib/i18n.ts`);
    }
  }
  for (const key of EXCLUDE_KEYS) {
    if (!webKeys.includes(key as keyof typeof STRINGS.en)) {
      throw new Error(`keys.ts EXCLUDE_KEYS entry "${key}" is not a key in lib/i18n.ts`);
    }
  }
  const entries: Entry[] = [];
  for (const key of webKeys) {
    if (!WEB_KEYS.some((p) => matches(p, key)) || EXCLUDE_KEYS.includes(key)) continue;
    const strip = STRIP_EMOJI.some((p) => matches(p, key));
    const pick = (lang: Lang) => {
      const s: string = STRINGS[lang][key];
      return strip ? stripLeadingEmoji(s) : s;
    };
    entries.push({ key, en: pick("en"), tr: pick("tr") });
  }
  for (const [key, text] of Object.entries(APP_STRINGS)) {
    if (key in STRINGS.en) throw new Error(`app string "${key}" shadows a web key`);
    entries.push({ key, en: text.en, tr: text.tr });
  }
  for (const key of REQUIRED_KEYS) {
    if (!entries.some((e) => e.key === key)) throw new Error(`required key "${key}" is not exported`);
  }
  return entries;
}

// --- Validation and grouping ------------------------------------------------

function placeholders(s: string): string[] {
  const seen: string[] = [];
  for (const m of s.matchAll(PLACEHOLDER)) if (!seen.includes(m[1])) seen.push(m[1]);
  return seen;
}

function toItems(entries: Entry[]): Item[] {
  const items: Item[] = [];
  const plurals = new Map<string, Partial<Record<"one" | "other", Entry>>>();
  const keys = new Set(entries.map((e) => e.key));
  for (const e of entries) {
    const m = /^(.*)\.(one|other)$/.exec(e.key);
    const bare = !m && keys.has(`${e.key}.one`) && !keys.has(`${e.key}.other`);
    if (m || bare) {
      const base = m ? m[1] : e.key;
      const group = plurals.get(base) ?? {};
      if (!plurals.has(base)) {
        plurals.set(base, group);
        // Placeholder item keeps the group in dictionary order.
        items.push({ kind: "plural", key: base, forms: { en: { one: "", other: "" }, tr: { one: "", other: "" } } });
      }
      group[m ? (m[2] as "one" | "other") : "other"] = e;
      continue;
    }
    const args = placeholders(e.en);
    const extra = placeholders(e.tr).filter((p) => !args.includes(p));
    if (extra.length) throw new Error(`"${e.key}": Turkish uses {${extra.join("}, {")}} which English lacks`);
    items.push({ kind: "string", key: e.key, text: { en: e.en, tr: e.tr }, args });
  }
  for (const item of items) {
    if (item.kind !== "plural") continue;
    const group = plurals.get(item.key);
    if (!group?.one || !group.other) throw new Error(`plural "${item.key}" needs both .one and .other`);
    for (const e of [group.one, group.other]) {
      const bad = [...placeholders(e.en), ...placeholders(e.tr)].filter((p) => p !== "n");
      if (bad.length) throw new Error(`plural "${e.key}" may only use {n}, found {${bad.join("}, {")}}`);
    }
    for (const lang of LANGS) item.forms[lang] = { one: group.one[lang], other: group.other[lang] };
  }
  return items;
}

// --- Names ------------------------------------------------------------------

/** "hero.titleLine1" -> "hero_title_line1" (Android resource name). */
function resName(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[.\-]/g, "_")
    .toLowerCase();
}

/** "hero.titleLine1" -> "heroTitleLine1" (Kotlin/Swift member name). */
function memberName(key: string): string {
  const parts = resName(key).split("_").filter(Boolean);
  return parts.map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join("");
}

const KEYWORDS = new Set([
  // Kotlin hard keywords and Swift keywords that can appear as slot names.
  "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
  "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
  "typeof", "val", "var", "when", "while", "default", "case", "func", "let", "self", "static",
  "struct", "enum", "import", "init", "repeat", "switch", "where", "guard", "defer", "protocol",
]);

function paramName(slot: string): string {
  // `lang` is the generated Swift accessors' own first parameter.
  if (slot === "lang") return "language";
  return KEYWORDS.has(slot) ? `${slot}Value` : slot;
}

function checkUnique(items: Item[]): void {
  const seen = new Map<string, string>();
  for (const item of items) {
    for (const name of [resName(item.key), memberName(item.key)]) {
      const other = seen.get(name);
      if (other && other !== item.key) throw new Error(`"${item.key}" and "${other}" both map to "${name}"`);
      seen.set(name, item.key);
    }
  }
}

// --- Formatting -------------------------------------------------------------

/** Positional format string: literal % doubled (only when it is formatted),
 * each slot replaced by its English-order index. */
function formatString(s: string, args: string[], spec: (index: number) => string): string {
  const escaped = args.length ? s.replace(/%/g, "%%") : s;
  return escaped.replace(PLACEHOLDER, (whole, name: string) => {
    const i = args.indexOf(name);
    return i < 0 ? whole : spec(i + 1);
  });
}

function androidEscape(s: string): string {
  let out = s
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    // aapt collapses runs of spaces and trims the ends; keep them literal.
    .replace(/ {2,}/g, (m) => " " + "\\u0020".repeat(m.length - 1))
    .replace(/^ | $/g, "\\u0020");
  if (out.startsWith("@") || out.startsWith("?")) out = `\\${out}`;
  return out;
}

function androidXml(items: Item[], lang: Lang): string {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} -->`, "<resources>"];
  for (const item of items) {
    if (item.kind === "string") {
      const raw = item.text[lang];
      const value = androidEscape(formatString(raw, item.args, (i) => `%${i}$s`));
      const formatted = !item.args.length && raw.includes("%") ? ' formatted="false"' : "";
      lines.push(`    <string name="${resName(item.key)}"${formatted}>${value}</string>`);
    } else {
      lines.push(`    <plurals name="${resName(item.key)}">`);
      for (const q of ["one", "other"] as const) {
        const value = androidEscape(formatString(item.forms[lang][q], ["n"], (i) => `%${i}$d`));
        lines.push(`        <item quantity="${q}">${value}</item>`);
      }
      lines.push("    </plurals>");
    }
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

function kotlin(items: Item[]): string {
  const members: string[] = [];
  const plain: string[] = [];
  for (const item of items) {
    const name = memberName(item.key);
    const id = resName(item.key);
    if (item.kind === "plural") {
      members.push(`    fun ${name}(n: Int): String = res.getQuantityString(R.plurals.${id}, n, n)`);
    } else if (item.args.length === 0) {
      members.push(`    val ${name}: String get() = res.getString(R.string.${id})`);
      plain.push(`        "${item.key}" -> R.string.${id}`);
    } else {
      const params = item.args.map((a) => `${paramName(a)}: String`).join(", ");
      const args = item.args.map(paramName).join(", ");
      members.push(`    fun ${name}(${params}): String = res.getString(R.string.${id}, ${args})`);
    }
  }
  return [
    `// ${HEADER}`,
    "package com.okjudge.judge.i18n",
    "",
    "import android.content.res.Resources",
    "import com.okjudge.judge.R",
    "",
    "/**",
    " * Typed access to the shared copy. Pass the Resources of the language to",
    " * render in (see AppLang), never rely on the process locale directly.",
    " */",
    "class Strings(private val res: Resources) {",
    ...members,
    "",
    "    /** A placeholder-free string by its lib/i18n.ts key, for keys built at",
    "     * runtime (\"badge.$type\", \"preset.$id.label\"). Null when unknown. */",
    "    fun text(key: String): String? = idOf(key)?.let { res.getString(it) }",
    "",
    "    companion object {",
    "        fun idOf(key: String): Int? = when (key) {",
    ...plain.map((l) => `    ${l}`),
    "            else -> null",
    "        }",
    "    }",
    "}",
    "",
  ].join("\n");
}

/** JSON in Xcode's own .xcstrings layout (sorted keys, `"key" : value`), so
 * opening the catalog in Xcode does not rewrite the whole file. */
function xcodeJson(value: unknown, indent = ""): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  const keys = Object.keys(value as object).sort();
  if (!keys.length) return "{\n\n}";
  const body = keys
    .map((k) => `${inner}${JSON.stringify(k)} : ${xcodeJson((value as Record<string, unknown>)[k], inner)}`)
    .join(",\n");
  return `{\n${body}\n${indent}}`;
}

function xcstrings(items: Item[]): string {
  const unit = (v: string) => ({ stringUnit: { state: "translated", value: v } });
  const strings: Record<string, unknown> = {};
  for (const item of items) {
    const localizations: Record<string, unknown> = {};
    for (const lang of LANGS) {
      if (item.kind === "string") {
        localizations[lang] = unit(formatString(item.text[lang], item.args, (i) => `%${i}$@`));
      } else {
        const form = (q: "one" | "other") => unit(formatString(item.forms[lang][q], ["n"], () => "%lld"));
        localizations[lang] = { variations: { plural: { one: form("one"), other: form("other") } } };
      }
    }
    strings[item.key] = { comment: HEADER, extractionState: "manual", localizations };
  }
  return `${xcodeJson({ sourceLanguage: "en", strings, version: "1.0" })}\n`;
}

function swift(items: Item[]): string {
  const members: string[] = [];
  const plain: string[] = [];
  for (const item of items) {
    const name = memberName(item.key);
    const key = JSON.stringify(item.key);
    if (item.kind === "plural") {
      members.push(`    static func ${name}(_ lang: AppLang, n: Int) -> String { format(${key}, lang, n) }`);
    } else if (item.args.length === 0) {
      members.push(`    static func ${name}(_ lang: AppLang) -> String { string(${key}, lang) }`);
      plain.push(`        ${key},`);
    } else {
      const params = item.args.map((a) => `${paramName(a)}: String`).join(", ");
      const args = item.args.map(paramName).join(", ");
      members.push(`    static func ${name}(_ lang: AppLang, ${params}) -> String { format(${key}, lang, ${args}) }`);
    }
  }
  return [
    `// ${HEADER}`,
    "import Foundation",
    "",
    "/// The two languages the app speaks. Strings are looked up in the matching",
    "/// .lproj bundle, so the in-app language never depends on the device locale.",
    "enum AppLang: String, CaseIterable, Codable, Sendable {",
    "    case en, tr",
    "",
    "    var bundle: Bundle {",
    '        Bundle.main.path(forResource: rawValue, ofType: "lproj").flatMap(Bundle.init(path:)) ?? .main',
    "    }",
    "",
    "    var locale: Locale { Locale(identifier: rawValue) }",
    "}",
    "",
    "/// Typed access to the shared copy.",
    "enum L10n {",
    ...members,
    "",
    "    /// A placeholder-free string by its lib/i18n.ts key, for keys built at",
    '    /// runtime ("badge.\\(type)"). Nil when unknown.',
    "    static func text(_ key: String, _ lang: AppLang) -> String? {",
    "        plainKeys.contains(key) ? string(key, lang) : nil",
    "    }",
    "",
    "    private static let plainKeys: Set<String> = [",
    ...plain,
    "    ]",
    "",
    "    private static func string(_ key: String, _ lang: AppLang) -> String {",
    "        NSLocalizedString(key, tableName: \"Localizable\", bundle: lang.bundle, comment: \"\")",
    "    }",
    "",
    "    private static func format(_ key: String, _ lang: AppLang, _ args: any CVarArg...) -> String {",
    "        String(format: string(key, lang), locale: lang.locale, arguments: args)",
    "    }",
    "}",
    "",
  ].join("\n");
}

// --- Main -------------------------------------------------------------------

function main(): void {
  const check = process.argv.includes("--check");
  const items = toItems(selectEntries());
  checkUnique(items);
  const outputs: [string, string][] = [
    [join(ANDROID_RES, "values/strings.xml"), androidXml(items, "en")],
    [join(ANDROID_RES, "values-tr/strings.xml"), androidXml(items, "tr")],
    [ANDROID_KT, kotlin(items)],
    [IOS_XCSTRINGS, xcstrings(items)],
    [IOS_SWIFT, swift(items)],
  ];
  let stale = 0;
  for (const [path, content] of outputs) {
    const rel = relative(REPO_DIR, path).replace(/\\/g, "/");
    if (check) {
      let current = "";
      try {
        current = readFileSync(path, "utf8");
      } catch {
        // missing counts as stale
      }
      if (current !== content) {
        stale++;
        console.error(`stale: ${rel}`);
      }
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, "utf8");
    console.log(`wrote ${rel}`);
  }
  const plurals = items.filter((i) => i.kind === "plural").length;
  console.log(`${items.length} entries (${plurals} plurals) in ${LANGS.join(", ")}`);
  if (stale) {
    console.error("Run: npx tsx mobile/shared/strings/export-strings.ts");
    process.exit(1);
  }
}

main();
